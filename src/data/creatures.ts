export interface VariantInfo {
  id: string;
  name: string;
  colors: string[];
  speciesId: string;
}

/** Color morphs that hatch from eggs; each counts as its own codex entry. */
export const VARIANT_BY_ID: Record<string, VariantInfo> = Object.fromEntries(
  SPECIES.flatMap((s) => (s.variants ?? []).map((v) => [v.id, { ...v, speciesId: s.id }])),
);

/** Giants (XL) don't breed: whales stay special. */
export function canBreed(s: Species) {
  return s.size !== "XL";
}

export function speciesForBiome(biome: BiomeId) {
  return SPECIES.filter((s) => s.biome === biome);
}

/** Egg-only species of a habitat (they hatch as surprises from its eggs). */
export function eggOnlySpecies(biome: BiomeId) {
  return SPECIES.filter((s) => s.biome === biome && s.obtain === "egg");
}

