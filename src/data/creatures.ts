// Species data. All balancing numbers for creatures live here.
//
// How species are obtained:
//  - obtain "shop": always buyable in its biome's shop for baseCost.
//  - obtain "visitor": appears as a visitor. If it also has a baseCost, it shows up
//    in the shop once you've befriended one (so uncommons become buyable later).
//    Legendary/rare species without baseCost can only be befriended.
//  - obtain "egg": reserved for egg-only species (breeding, build step 9).

import type { BiomeId } from "./biomes";

export type Size = "S" | "M" | "L" | "XL";
export type Rarity = "common" | "uncommon" | "rare" | "legendary";
export type Activity = "day" | "night" | "always";
export type Behavior = "school" | "wander" | "bottom" | "surface" | "cruise" | "hover";

export interface Species {
  id: string;
  name: string;
  scientific?: string;
  biome: BiomeId;
  size: Size;
  rarity: Rarity;
  obtain: "shop" | "visitor" | "egg";
  baseCost?: number;
  pearlsPerSec: number;
  activity: Activity;
  behavior: Behavior;
  /** [body, secondary, accent]. Drawn from the biome palette + one accent. */
  colors: string[];
  variants?: { id: string; name: string; colors: string[] }[];
  /** Real-world size, metric. */
  realSize: string;
  habitat: string;
  fact: string;
  /** Odds of also showing up as a visitor, for species that aren't visitor-only. */
  visitorWeight?: number;
  /** For schooling species: how many fish one purchase shows in the habitat. */
  schoolSize?: number;
  /** Special move: dolphins jump, humpbacks breach, sperm whales dive in from above. */
  trick?: "jump" | "breach" | "dive";
  /** Optional .glb to replace the procedural model. */
  modelUrl?: string;
}

/** Space points each size uses in a habitat. */
